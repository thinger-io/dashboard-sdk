// Writes src/version.ts from package.json, so the SDK reports the version it is published as.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const { version } = JSON.parse(readFileSync(root + 'package.json', 'utf8'));
const file = root + 'src/version.ts';
const content = `// Generated by scripts/version.mjs from package.json: do not edit.\nexport const SDK_VERSION = '${version}';\n`;
let current = '';
try {
    current = readFileSync(file, 'utf8');
} catch {}
if (current !== content) writeFileSync(file, content);
